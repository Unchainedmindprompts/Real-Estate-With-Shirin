/** Validate the shape of this file. Returns an array of problem strings. */
export function validateAllowlistShape() {
  const problems = []
  const check = (list, label, key) => {
    if (!Array.isArray(list)) {
      problems.push(`${label} must be an array.`)
      return
    }
    list.forEach((entry, i) => {
      if (!entry || typeof entry !== 'object') {
        problems.push(`${label}[${i}] must be an object.`)
        return
      }
      if (!entry[key] || typeof entry[key] !== 'string' || entry[key].trim() === '') {
        problems.push(`${label}[${i}] is missing a non-empty "${key}".`)
      }
      if (!entry.reason || typeof entry.reason !== 'string' || entry.reason.trim() === '') {
        problems.push(`${label}[${i}] (${entry[key] ?? 'unknown'}) is missing a non-empty "reason".`)
      }
    })
  }
  check(sitemapExclusions, 'sitemapExclusions', 'route')
  check(allowedNonRoutePaths, 'allowedNonRoutePaths', 'path')
  check(allowedQueryParams, 'allowedQueryParams', 'param')
  check(allowedAssetPaths, 'allowedAssetPaths', 'path')
  return problems
}
